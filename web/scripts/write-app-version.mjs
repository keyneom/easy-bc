import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const gradlePath = path.resolve(root, "../android/app/build.gradle.kts");
const gradle = fs.readFileSync(gradlePath, "utf8");
const match = gradle.match(/versionName\s*=\s*"([^"]+)"/);
if (!match) {
  throw new Error(`Could not read versionName from ${gradlePath}`);
}

const version = match[1];
const publishedAt = new Date().toISOString();
const payload = { version, publishedAt };

fs.mkdirSync(path.join(root, "public"), { recursive: true });
fs.mkdirSync(path.join(root, "src/generated"), { recursive: true });

fs.writeFileSync(
  path.join(root, "public/version.json"),
  `${JSON.stringify(payload, null, 2)}\n`,
);
fs.writeFileSync(
  path.join(root, "src/generated/appVersion.ts"),
  `/** Generated by scripts/write-app-version.mjs — do not edit. */\nexport const APP_VERSION = ${JSON.stringify(version)};\n`,
);

console.log(`EasyBC app version: ${version}`);
